"""Write a Yosys memory_libmap library and its Verilog technology map."""


class yosys:

    def __init__(self, sram):
        self.sram = sram

    def write(self, library_name, map_name):
        sram = self.sram
        if sram.num_banks != 1:
            raise ValueError("Yosys mapping requires a single-bank SRAM")
        if sram.num_spare_rows:
            raise ValueError("Yosys mapping does not support spare rows")
        if sram.num_words != 2 ** sram.addr_size:
            raise ValueError("Yosys mapping requires a power-of-two memory depth")

        cell_name = "$__OPENRAM_{}".format(sram.name)
        with open(library_name, "w") as library:
            library.write("ram block {} {{\n".format(cell_name))
            library.write("    abits {};\n".format(sram.addr_size))
            library.write("    width {};\n".format(sram.word_size))
            # Estimate cost in 64-bit units so larger macros have a higher cost.
            library.write("    cost {};\n".format(sram.num_words * sram.word_size / 64))
            library.write("    init none;\n")
            for port in sram.all_ports:
                if port in sram.readwrite_ports:
                    kind = "srsw"
                elif port in sram.write_ports:
                    kind = "sw"
                else:
                    kind = "sr"
                library.write('    port {} "P{}" {{\n'.format(kind, port))
                library.write("        clock posedge;\n")
                if port in sram.readwrite_ports:
                    library.write("        rdwr undefined;\n")
                library.write("    }\n")
            library.write("}\n")

        declarations = []
        unused_outputs = []
        connections = []
        for port in sram.all_ports:
            prefix = "PORT_P{}_".format(port)
            declarations.append("input {}CLK".format(prefix))
            declarations.append("input [{}:0] {}ADDR".format(sram.addr_size - 1, prefix))
            connections.append(".clk{}({}CLK)".format(port, prefix))
            connections.append(".addr{}({}ADDR)".format(port, prefix))
            if port in sram.write_ports:
                declarations.append("input {}WR_EN".format(prefix))
                declarations.append("input [{}:0] {}WR_DATA".format(sram.word_size - 1, prefix))
                write_data = "{}WR_DATA".format(prefix)
                if sram.num_spare_cols:
                    write_data = "{{{}'b0, {}}}".format(sram.num_spare_cols, write_data)
                    connections.append(".spare_wen{}({}'b0)".format(port, sram.num_spare_cols))
                connections.append(".din{}({})".format(port, write_data))
                if sram.write_size != sram.word_size:
                    masks = (sram.word_size + sram.write_size - 1) // sram.write_size
                    connections.append(".wmask{}({}'b{})".format(port, masks, "1" * masks))
            if port in sram.read_ports:
                declarations.append("output [{}:0] {}RD_DATA".format(sram.word_size - 1, prefix))
                read_data = "{}RD_DATA".format(prefix)
                if sram.num_spare_cols:
                    unused_outputs.append("wire [{}:0] unused_dout{};".format(sram.num_spare_cols - 1, port))
                    read_data = "{{unused_dout{}, {}}}".format(port, read_data)
                connections.append(".dout{}({})".format(port, read_data))
            if port in sram.readwrite_ports:
                connections.append(".csb{}(1'b0)".format(port))
                connections.append(".web{}(~{}WR_EN)".format(port, prefix))
            elif port in sram.write_ports:
                connections.append(".csb{}(~{}WR_EN)".format(port, prefix))
            else:
                connections.append(".csb{}(1'b0)".format(port))

        with open(map_name, "w") as mapping:
            mapping.write("// Generated by OpenRAM for Yosys memory_libmap.\n")
            mapping.write("// Use full-word writes so read data during a write may be undefined.\n")
            mapping.write("module \\{} (\n    {}\n);\n".format(cell_name, ",\n    ".join(declarations)))
            for declaration in unused_outputs:
                mapping.write("    {}\n".format(declaration))
            mapping.write("    {} _TECHMAP_REPLACE_ (\n        {}\n    );\n".format(
                sram.name, ",\n        ".join(connections)))
            mapping.write("endmodule\n")
